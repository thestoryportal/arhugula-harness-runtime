"""A loaded deployment, and the one way its configuration changes.

[LAW:single-enforcer] `apply` is the only writer of the answers file, of generated
configs and of the provider wrappers they name. It renders every config to a staging
directory, has the runtime's own loader accept each one, and only then moves them into
place, rewrites the wrappers and saves the answers. A change the runtime refuses leaves
the deployment exactly as it was.
"""

from __future__ import annotations

import fcntl
import json
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from arhugula_kit import modelwrap, render, runtime, spec, toml_out
from arhugula_kit.errors import Exit, KitError
from arhugula_kit.layout import Home
from arhugula_kit.spec import Spec

__all__ = ["Deployment", "apply", "open_deployment"]


@dataclass(frozen=True)
class Deployment:
    home: Home
    spec: Spec
    fragments: dict[str, render.Fragment]

    def target(self, project: str | None = None) -> render.Target:
        """The config target for a project name, the current project, or the default."""
        name = self.spec.current_project if project is None else project
        for target in render.targets(self.spec, self.home):
            if target.name == name:
                return target
        attached = ", ".join(sorted(self.spec.projects)) or "none"
        raise KitError(
            Exit.PRECONDITION,
            f"no attached project named {name!r} (attached: {attached})",
            fix="arhugula project add <path>",
        )


def open_deployment(home: Home | None = None) -> Deployment:
    home = home or Home.of_kit()
    known = render.fragments()
    return Deployment(home, spec.load(home.spec_file, known_features=tuple(known)), known)


def apply(deployment: Deployment, changed: Spec) -> Deployment:
    """Regenerate every config from `changed`; commit only when the runtime accepts them all.

    The changed answers go through the same parser as the file does, so a verb cannot
    save a state that the next command would refuse to load. One `arhugula` command at a
    time changes the configuration; a second one is told so, not interleaved.
    """
    home = deployment.home
    runtime.require_installed(home)
    known = tuple(deployment.fragments)
    # Through JSON, exactly as the file would be read back.
    changed = spec.parse(json.loads(json.dumps(changed.to_json())), known_features=known)
    home.config.mkdir(parents=True, exist_ok=True)
    with (home.config / ".lock").open("w") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise KitError(
                Exit.PRECONDITION,
                "another `arhugula` command is changing this deployment's configuration",
                fix="wait for it to finish, then run this command again",
            ) from None
        changed = render.with_new_cutover_ledgers(changed, home)
        wrappers = render.wrappers(changed, home)
        staging = Path(tempfile.mkdtemp(prefix=".staging-", dir=home.config))
        staged: list[tuple[Path, Path]] = []
        try:
            for index, target in enumerate(render.targets(changed, home)):
                document = render.render_config(changed, home, target, deployment.fragments)
                scratch = staging / f"{index}.toml"
                scratch.write_text(
                    toml_out.dumps(document, header=render.header(target, home)), encoding="utf-8"
                )
                match runtime.ask(home, "load-config", config=str(scratch)):
                    case runtime.Refusal(kind=kind, message=message):
                        raise KitError(
                            Exit.RUNTIME_REFUSED,
                            f"the runtime refuses the new config for {target.label} ({kind}): "
                            f"{message}\nNothing was changed.",
                        )
                    case _:
                        staged.append((scratch, target.config_file))
            # The answers are the source: once they are saved, any config that did not
            # make it into place is regenerated by the next verb or `init --reverify`.
            spec.save(changed, home.spec_file)
            # Before the configs that name them, so no config ever points at a missing wrapper.
            modelwrap.sync(home, wrappers)
            wanted = {final for _, final in staged}
            for scratch, final in staged:
                final.parent.mkdir(parents=True, exist_ok=True)
                scratch.replace(final)
            for stale in (home.config / "projects").glob("*.toml"):
                if stale not in wanted:
                    stale.unlink()
        finally:
            shutil.rmtree(staging, ignore_errors=True)
    return Deployment(home, changed, deployment.fragments)
