"""The wrapper that turns `<model>@<level>` into a provider CLI's own thinking-level option.

The runtime calls a CLI provider with a model and nothing else: it has no thinking-level
setting for these CLI kinds. So the kit configures a small generated script as the
provider's `command`. The runtime's argv reaches the script; the script splits a model
written `<model>@<level>` and hands the real CLI its model and its level option. Every
other argument goes through byte for byte, the sign-in check's argv included.

[LAW:one-source-of-truth] What the option looks like for each CLI is the provider
catalogue's (`model_flag`, `level_args`); this module only writes it down as a script.
"""

from __future__ import annotations

import stat
from collections.abc import Mapping
from pathlib import Path

from arhugula_kit.layout import Home
from arhugula_kit.providers import Provider

__all__ = ["MARK", "PREFIX", "is_generated", "path", "script", "sync"]

PREFIX = "provider-"
MARK = "# GENERATED by the Arhugula kit for the provider"
"""The line that tells a wrapper the kit wrote from a file of the operator's own."""


def path(home: Home, provider: Provider) -> Path:
    return home.bin / f"{PREFIX}{provider.name}"


def is_generated(file: Path) -> bool:
    """Whether `file` is a wrapper the kit wrote: its second line is the kit's mark."""
    if not file.is_file():
        return False
    with file.open("rb") as handle:
        lines = [handle.readline() for _ in range(2)]
    return lines[1].decode("utf-8", "replace").startswith(MARK)


def _single_quoted(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def _level_word(template: str) -> str:
    """One word of the CLI's level option as a zsh double-quoted word; `{level}` becomes the level."""
    escaped = "".join("\\" + char if char in '\\"$`' else char for char in template)
    return '"' + escaped.replace("{level}", "${level}") + '"'


def script(provider: Provider, real: str) -> str:
    """The wrapper's text for one provider, with the real executable's path written in."""
    level_words = " ".join(_level_word(word) for word in provider.level_args)
    return f"""#!/bin/zsh -f
{MARK} `{provider.name}`. Do not edit: it is
# rewritten whenever the configuration is. The runtime runs this in place of the CLI. A
# model written <model>@<level> becomes the CLI's own model and thinking-level options;
# every other argument is passed through unchanged. Nothing is logged.
real={_single_quoted(real)}
if [[ ! -x $real ]]; then
  print -u2 -r -- "arhugula: the {provider.title} executable is gone: $real"
  print -u2 -r -- "  fix: arhugula provider enable {provider.name} --command <path-to-{provider.command}>"
  exit 127
fi
# zsh drops empty words from an unquoted array, and an empty argument can carry meaning
# for the CLI, so every word is copied and passed on quoted.
out=()
integer i=1 seen=0
while (( i <= $# )); do
  word=${{@[i]}}
  if (( ! seen )) && [[ $word == {_single_quoted(provider.model_flag)} ]] && (( i < $# )) && [[ ${{@[i+1]}} == ?*@?* ]]; then
    model=${{@[i+1]}}
    level=${{model##*@}}
    out+=("$word" "${{model%@*}}" {level_words})
    seen=1
    (( i += 2 ))
  else
    out+=("$word")
    (( i += 1 ))
  fi
done
exec "$real" "${{out[@]}}"
"""


def sync(home: Home, wanted: Mapping[Path, str]) -> None:
    """Make the kit's wrappers under `<home>/bin` exactly `wanted`: write each, remove any other.

    Only a file the kit wrote is removed; a `provider-*` file of the operator's own stays.
    """
    home.bin.mkdir(parents=True, exist_ok=True)
    for stale in home.bin.glob(f"{PREFIX}*"):
        if stale not in wanted and is_generated(stale):
            stale.unlink()
    for target, text in wanted.items():
        scratch = target.with_name(f".{target.name}.tmp")
        scratch.write_text(text, encoding="utf-8")
        scratch.chmod(scratch.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        scratch.replace(target)
