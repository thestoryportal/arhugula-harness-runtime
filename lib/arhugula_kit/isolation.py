"""Isolation tier 3: tool execution under gVisor inside the Lima VM.

The runtime runs every stdio MCP tool at tier 3 and refuses when no tier-3 driver is
configured. gVisor is Linux-only, so the driver reaches the VM's Docker engine through
one wrapper script the kit writes. The span labels (`gvisor` / `runsc`) are left for the
runtime to derive from the tier it actually delivers.
"""

from __future__ import annotations

import stat
from collections.abc import Callable
from dataclasses import replace
from pathlib import Path
from typing import Any

from arhugula_kit import deploy, lima, overlay
from arhugula_kit.deploy import Deployment
from arhugula_kit.errors import Exit, KitError
from arhugula_kit.layout import Home

__all__ = ["ECHO_CLIENT", "attach", "disable", "enable_tier3", "engine_of", "wrapper_path"]

ECHO_CLIENT = "sandbox-echo"
ECHO_IMAGE = "alpine:3.20"
# Upstream's demonstration runner: it echoes the request's "value" argument back as an
# MCP text result. It handles plain ASCII values only; a real tool needs its own image.
ECHO_COMMAND = [
    "sh",
    "-c",
    'v=$(sed -n "s/.*\\"value\\"[[:space:]]*:[[:space:]]*\\"\\([^\\"]*\\)\\".*/\\1/p" | head -n 1); '
    'printf "{\\"content\\":[{\\"type\\":\\"text\\",\\"text\\":\\"%s\\"}],\\"isError\\":false}" "$v"',
]
MCP_CLIENTS = ("runtime", "mcp_clients")


def wrapper_path(home: Home) -> Path:
    return home.bin / "gvisor-docker"


def engine_of(deployment: Deployment, *, start: bool) -> lima.Engine:
    """The Docker engine of the deployment's Lima instance, starting the VM when asked."""
    chosen = deployment.spec.observability
    if not chosen.instance:
        raise KitError(
            Exit.PRECONDITION,
            "no Lima instance is configured for this deployment",
            fix="arhugula init --reconfigure, and answer question 11 with `<lima-home>::<instance>`",
        )
    found = [
        instance
        for home in lima.candidate_homes(chosen.lima_home)
        for instance in lima.instances(home)
        if instance.name == chosen.instance
    ]
    if not found:
        raise KitError(
            Exit.PRECONDITION,
            f"no Lima instance {chosen.instance!r} under {chosen.lima_home}",
            fix="check that the volume holding the Lima home is mounted",
        )
    instance = found[0]
    if not instance.running:
        if not start:
            raise KitError(
                Exit.PRECONDITION,
                f"the Lima instance {instance.name} is stopped",
                fix="arhugula observability up",
            )
        instance.start()
        instance = instance.refreshed()
    engine = lima.probe_engine(instance)
    if engine is None:
        raise KitError(
            Exit.EXTERNAL_TOOL,
            f"no Docker engine answers inside {instance.name}",
            fix=f"LIMA_HOME={instance.lima_home} limactl shell {instance.name} docker info",
        )
    return engine


def _write_wrapper(home: Home, engine: lima.Engine) -> Path:
    path = wrapper_path(home)
    path.parent.mkdir(parents=True, exist_ok=True)
    words = " ".join(engine.docker_words)
    path.write_text(
        "#!/bin/sh\n"
        "# GENERATED by `arhugula isolation enable tier-3`. The runtime runs this as its\n"
        "# container CLI: it is the Docker engine inside the Lima VM, never Docker Desktop.\n"
        f'exec env LIMA_HOME="{engine.instance.lima_home}" limactl shell '
        f'"{engine.instance.name}" {words} "$@"\n',
        encoding="utf-8",
    )
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def _driver(home: Home, image: str, command: list[str]) -> dict[str, Any]:
    return {
        "image": image,
        "command": command,
        "network": "none",
        "docker_binary": "{{HOME}}/bin/gvisor-docker",
        "timeout_seconds": 30.0,
    }


def _clients(deployment: Deployment) -> list[dict[str, Any]]:
    return list(overlay.get(deployment.spec.overlay, MCP_CLIENTS, []))


def enable_tier3(deployment: Deployment, *, out: Callable[[str], None] = print) -> Deployment:
    """Check gVisor, write the wrapper, and add the kit's sandboxed echo client."""
    engine = engine_of(deployment, start=True)
    if not engine.has_gvisor:
        raise KitError(
            Exit.PRECONDITION,
            f"the Docker engine inside {engine.instance.name} lists no `runsc` runtime "
            f"(it lists: {', '.join(engine.runtimes) or 'none'})",
            fix="install gVisor in the VM and register it with Docker under the name `runsc`",
        )
    out(f"  gVisor runtime `runsc` is registered in {engine.instance.name}")
    out(f"  wrote {_write_wrapper(deployment.home, engine)}")
    pulled = engine.docker("pull", ECHO_IMAGE, timeout=600)
    if not pulled.ok:
        raise KitError(Exit.EXTERNAL_TOOL, f"could not pull {ECHO_IMAGE} in the VM:\n{pulled.last_lines()}")
    out(f"  image {ECHO_IMAGE} is present in the VM")
    echo = {
        "client_name": ECHO_CLIENT,
        "transport": "stdio",
        "trust_level": "L1_SIGNED_PINNED",
        "blast_radius": "READ_ONLY",
        "connection_url": "stdio://{{HOME}}/env/bin/python "
        "{{UPSTREAM}}/deploy/self-hosted-local/mcp_echo_server.py",
        "default_blast_radius": "READ_ONLY",
        "sandbox_driver": _driver(deployment.home, ECHO_IMAGE, ECHO_COMMAND),
    }
    clients = [c for c in _clients(deployment) if c["client_name"] != ECHO_CLIENT] + [echo]
    changed = overlay.set_value(
        replace(deployment.spec, isolation_tier3=True), "", MCP_CLIENTS, clients
    )
    deployment = deploy.apply(deployment, changed)
    out(f"  MCP client `{ECHO_CLIENT}` runs its tool under gVisor; try it with:")
    out("    arhugula run deploy/self-hosted-local/r420-tool-echo.toml --project default")
    return deployment


def attach(deployment: Deployment, client: str, image: str, command: list[str]) -> Deployment:
    """Give one of the operator's MCP clients a tier-3 driver."""
    if not wrapper_path(deployment.home).is_file():
        raise KitError(
            Exit.PRECONDITION, "isolation tier 3 is not enabled", fix="arhugula isolation enable tier-3"
        )
    clients = _clients(deployment)
    if not any(c["client_name"] == client for c in clients):
        raise KitError(Exit.PRECONDITION, f"no MCP client named {client!r}", fix="arhugula mcp list")
    engine = engine_of(deployment, start=True)
    pulled = engine.docker("pull", image, timeout=900)
    if not pulled.ok:
        raise KitError(Exit.EXTERNAL_TOOL, f"could not pull {image} in the VM:\n{pulled.last_lines()}")
    updated = [
        {**c, "sandbox_driver": _driver(deployment.home, image, command)} if c["client_name"] == client else c
        for c in clients
    ]
    return deploy.apply(deployment, overlay.set_value(deployment.spec, "", MCP_CLIENTS, updated))


def disable(deployment: Deployment) -> Deployment:
    """Remove the sandboxed echo client and every tier-3 driver; keep the operator's clients."""
    kept = [
        {k: v for k, v in c.items() if k != "sandbox_driver"}
        for c in _clients(deployment)
        if c["client_name"] != ECHO_CLIENT
    ]
    spec = replace(deployment.spec, isolation_tier3=False)
    changed = overlay.set_value(spec, "", MCP_CLIENTS, kept) if kept else overlay.dropped(spec, "", MCP_CLIENTS)
    deployment = deploy.apply(deployment, changed)
    wrapper = wrapper_path(deployment.home)
    if wrapper.is_file():
        wrapper.unlink()
    return deployment
